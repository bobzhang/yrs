#!/usr/bin/env python3
"""Generate portable character classes matching the pinned Rust oracle toolchain."""
import json,subprocess
from pathlib import Path
root=Path(__file__).resolve().parent.parent
result=subprocess.run(['cargo','+1.97.1','run','--release','--locked','--manifest-path','validation/rust/Cargo.toml','--bin','path_unicode'],cwd=root,text=True,capture_output=True,check=True)
data=json.loads(result.stdout)
lines=['// Generated by validation/generate_path_unicode.py using Rust 1.97.1.',f'// Unicode {".".join(map(str,data["unicode"]))}; half-open scalar ranges.']
for name in ['alphabetic','numeric']:
 lines+=['','///|',f'let path_{name}_ranges : ReadOnlyArray[(Int, Int)] = [']
 lines += [f'  (0x{a:x}, 0x{b:x}),' for a,b in data[name]]
 lines+= [']']
(root/'json_path_unicode.mbt').write_text('\n'.join(lines)+'\n')
print({key:len(data[key]) for key in ['alphabetic','numeric']})
